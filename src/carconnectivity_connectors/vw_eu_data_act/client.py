def _http_token(value: str) -> str:
    """Return ``value`` reduced to an RFC 9110 token (User-Agent product syntax)."""
    return re.sub(r"[^!#$%&'*+\-.^_`|~0-9A-Za-z]", "-", value).strip("-") or "unknown"


